export const SESSION_STATES=Object.freeze({
  PRESENTATION:'presentation',
  ATTEMPT:'attempt',
  HELP:'help',
  RETRY:'retry',
  RESOLUTION:'resolution',
  RESULT:'result'
});

export const SESSION_EVENTS=Object.freeze({
  BEGIN_ATTEMPT:'begin_attempt',
  REQUEST_HELP:'request_help',
  INCORRECT:'incorrect',
  CORRECT:'correct',
  SHOW_SOLUTION:'show_solution',
  BEGIN_RETRY:'begin_retry',
  NEXT_ROUND:'next_round',
  COMPLETE_SESSION:'complete_session',
  RESET:'reset'
});

const TRANSITIONS=Object.freeze({
  [SESSION_STATES.PRESENTATION]:Object.freeze({
    [SESSION_EVENTS.BEGIN_ATTEMPT]:SESSION_STATES.ATTEMPT,
    [SESSION_EVENTS.REQUEST_HELP]:SESSION_STATES.HELP,
    [SESSION_EVENTS.CORRECT]:SESSION_STATES.RESOLUTION,
    [SESSION_EVENTS.INCORRECT]:SESSION_STATES.RETRY,
    [SESSION_EVENTS.SHOW_SOLUTION]:SESSION_STATES.RESOLUTION
  }),
  [SESSION_STATES.ATTEMPT]:Object.freeze({
    [SESSION_EVENTS.REQUEST_HELP]:SESSION_STATES.HELP,
    [SESSION_EVENTS.CORRECT]:SESSION_STATES.RESOLUTION,
    [SESSION_EVENTS.INCORRECT]:SESSION_STATES.RETRY,
    [SESSION_EVENTS.SHOW_SOLUTION]:SESSION_STATES.RESOLUTION
  }),
  [SESSION_STATES.HELP]:Object.freeze({
    [SESSION_EVENTS.BEGIN_RETRY]:SESSION_STATES.RETRY,
    [SESSION_EVENTS.CORRECT]:SESSION_STATES.RESOLUTION,
    [SESSION_EVENTS.INCORRECT]:SESSION_STATES.RETRY,
    [SESSION_EVENTS.SHOW_SOLUTION]:SESSION_STATES.RESOLUTION
  }),
  [SESSION_STATES.RETRY]:Object.freeze({
    [SESSION_EVENTS.REQUEST_HELP]:SESSION_STATES.HELP,
    [SESSION_EVENTS.CORRECT]:SESSION_STATES.RESOLUTION,
    [SESSION_EVENTS.INCORRECT]:SESSION_STATES.RETRY,
    [SESSION_EVENTS.SHOW_SOLUTION]:SESSION_STATES.RESOLUTION
  }),
  [SESSION_STATES.RESOLUTION]:Object.freeze({
    [SESSION_EVENTS.NEXT_ROUND]:SESSION_STATES.PRESENTATION,
    [SESSION_EVENTS.COMPLETE_SESSION]:SESSION_STATES.RESULT
  }),
  [SESSION_STATES.RESULT]:Object.freeze({
    [SESSION_EVENTS.RESET]:SESSION_STATES.PRESENTATION
  })
});

export function sessionTransition(state,event){
  const current=Object.values(SESSION_STATES).includes(state)?state:SESSION_STATES.PRESENTATION;
  return TRANSITIONS[current]?.[event]||current;
}

export function createSessionState(){return SESSION_STATES.PRESENTATION;}

export function isSessionResolved(state){return state===SESSION_STATES.RESOLUTION||state===SESSION_STATES.RESULT;}

export function allowedSessionEvents(state){return Object.keys(TRANSITIONS[state]||{});}
